const { isAuthenticated } = require("../lib/auth");

/**
 * 유튜브 영상 URL에서 자막(캡션)을 추출해 순수 텍스트로 반환한다.
 * 별도 라이브러리 없이, 영상 시청 페이지 HTML 안에 박혀있는 captionTracks 정보를
 * 찾아서(유튜브 자막 다운로더들이 흔히 쓰는 방식) 자막 트랙 URL을 얻고,
 * 그 트랙을 json3 포맷으로 받아 텍스트만 이어붙인다.
 */

function extractVideoId(rawUrl) {
  let u;
  try {
    u = new URL(rawUrl);
  } catch (e) {
    return null;
  }
  const host = u.hostname.replace(/^www\./, "");
  if (host === "youtu.be") {
    const id = u.pathname.split("/").filter(Boolean)[0];
    return id || null;
  }
  if (host === "youtube.com" || host === "m.youtube.com" || host === "music.youtube.com") {
    const parts = u.pathname.split("/").filter(Boolean);
    if (parts[0] === "shorts" && parts[1]) return parts[1];
    if (parts[0] === "embed" && parts[1]) return parts[1];
    if (parts[0] === "live" && parts[1]) return parts[1];
    const v = u.searchParams.get("v");
    if (v) return v;
  }
  return null;
}

function decodeEntities(text) {
  return text
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/\\n/g, "\n")
    .replace(/\\u0026/g, "&");
}

function pickBestTrack(tracks) {
  if (!tracks || !tracks.length) return null;
  const byLang = (code) => tracks.find((t) => (t.languageCode || "").toLowerCase() === code);
  return (
    byLang("ko") ||
    tracks.find((t) => (t.languageCode || "").toLowerCase().startsWith("ko")) ||
    byLang("en") ||
    tracks.find((t) => (t.languageCode || "").toLowerCase().startsWith("en")) ||
    tracks[0]
  );
}

module.exports = async (req, res) => {
  if (!isAuthenticated(req)) {
    res.status(401).json({ error: "로그인이 필요해요." });
    return;
  }
  const rawUrl = req.query.url;
  if (!rawUrl) {
    res.status(400).json({ error: "url이 필요해요." });
    return;
  }
  const videoId = extractVideoId(rawUrl);
  if (!videoId) {
    res.status(400).json({ error: "유튜브 영상 URL에서 영상 ID를 찾지 못했어요. 링크 형식을 확인해주세요." });
    return;
  }

  const commonHeaders = {
    "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36",
    "Accept-Language": "ko-KR,ko;q=0.9,en;q=0.8",
  };

  let html;
  try {
    const pageRes = await fetch(`https://www.youtube.com/watch?v=${encodeURIComponent(videoId)}&hl=ko`, {
      headers: commonHeaders,
    });
    if (!pageRes.ok) {
      res.status(502).json({ error: `유튜브 페이지를 가져오지 못했어요 (상태 코드 ${pageRes.status}).` });
      return;
    }
    html = await pageRes.text();
  } catch (e) {
    res.status(500).json({ error: "유튜브 페이지 요청 중 오류가 발생했어요: " + e.message });
    return;
  }

  // 제목 추출 (실패해도 치명적이지 않으니 best-effort)
  let title = "";
  const titleMatch = html.match(/<meta name="title" content="([^"]*)"/);
  if (titleMatch) title = decodeEntities(titleMatch[1]);

  // captionTracks 추출: 유튜브 자막 다운로더들이 흔히 쓰는, 페이지에 박힌 JSON을 문자열로 잘라내는 방식
  const marker = '"captionTracks":';
  const markerIdx = html.indexOf(marker);
  if (markerIdx < 0) {
    res.status(422).json({
      error: "이 영상은 자막(캡션)을 찾을 수 없어요. 자막이 있는 영상을 사용하거나, 내용을 텍스트로 직접 붙여넣어주세요.",
    });
    return;
  }
  let tracks = [];
  try {
    const after = html.slice(markerIdx + marker.length);
    const jsonStr = after.split(',"videoDetails')[0];
    tracks = JSON.parse(jsonStr);
  } catch (e) {
    res.status(422).json({
      error: "자막 목록을 읽는 데 실패했어요. 내용을 텍스트로 직접 붙여넣어주세요.",
    });
    return;
  }

  const track = pickBestTrack(tracks);
  if (!track || !track.baseUrl) {
    res.status(422).json({
      error: "사용할 수 있는 자막 트랙을 찾지 못했어요. 내용을 텍스트로 직접 붙여넣어주세요.",
    });
    return;
  }

  let transcriptText = "";
  try {
    const trackUrl = track.baseUrl.replace(/\\u0026/g, "&") + "&fmt=json3";
    const capRes = await fetch(trackUrl, { headers: commonHeaders });
    if (!capRes.ok) throw new Error("자막 응답 실패 (상태 " + capRes.status + ")");
    const data = await capRes.json();
    const lines = [];
    (data.events || []).forEach((ev) => {
      if (!ev.segs) return;
      const line = ev.segs.map((s) => s.utf8 || "").join("");
      if (line && line.trim() && line.trim() !== "\n") lines.push(line.trim());
    });
    transcriptText = lines.join(" ").replace(/\s+/g, " ").trim();
  } catch (e) {
    res.status(500).json({ error: "자막 내용을 가져오는 중 오류가 발생했어요: " + e.message });
    return;
  }

  if (transcriptText.length < 30) {
    res.status(422).json({
      error: "자막에서 충분한 텍스트를 추출하지 못했어요. 내용을 텍스트로 직접 붙여넣어주세요.",
    });
    return;
  }

  const truncated = transcriptText.length > 12000;
  const text = truncated ? transcriptText.slice(0, 12000) : transcriptText;
  res.status(200).json({
    text,
    title,
    videoId,
    languageCode: track.languageCode || "",
    isAutoGenerated: track.kind === "asr",
    truncated,
  });
};
